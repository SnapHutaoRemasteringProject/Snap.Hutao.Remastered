using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Migrations;
using Microsoft.EntityFrameworkCore.Migrations.Operations;
using Microsoft.EntityFrameworkCore.Storage;
using Snap.Hutao.Remastered.Model.Entity.Database;
using System.Security.Cryptography;
using System.Text;

namespace Snap.Hutao.Remastered.Service;

internal static class Program
{
    private static int Main(string[] args)
    {
        if (args.Length is not 1 and not 2 || args.Length == 2 && args[1] is not "--check" and not "--verify")
        {
            Console.Error.WriteLine("Usage: schema-tool <repository-root> [--check|--verify]");
            return 2;
        }

        string root = Path.GetFullPath(args[0]);
        if (args.Length == 2 && args[1] == "--verify")
        {
            SchemaVerifier.Verify();
            return 0;
        }
        string app = Path.Combine(root, "src/Snap.Hutao.Remastered/Snap.Hutao.Remastered");
        string output = Path.Combine(app, "Core/Database/Schema");
        bool check = args.Length == 2;
        using AppDbContext context = new(new DbContextOptionsBuilder<AppDbContext>().UseSqlite("Data Source=:memory:").Options);
        IMigrationsAssembly assembly = context.GetService<IMigrationsAssembly>();
        IMigrationsSqlGenerator sqlGenerator = context.GetService<IMigrationsSqlGenerator>();
        IModelRuntimeInitializer modelInitializer = context.GetService<IModelRuntimeInitializer>();
        IHistoryRepository history = context.GetService<IHistoryRepository>();
        string[] migrations = context.Database.GetMigrations().ToArray();
        Dictionary<string, string> files = new(StringComparer.Ordinal);
        StringBuilder catalog = new("// <auto-generated />\n// Generate with tools/Snap.Hutao.Database.Schema; do not edit.\n\nnamespace Snap.Hutao.Remastered.Core.Database;\n\ninternal static class DatabaseMigrations\n{\n    public static readonly DatabaseMigration[] All =\n    [\n");

        for (int index = 0; index < migrations.Length; index++)
        {
            string id = migrations[index];
            Migration migration = assembly.CreateMigration(assembly.Migrations[id], context.Database.ProviderName!);
            if (id == "20260805125557_AddBackpackReliquaryScoreConfig")
            {
                // The historical migration calls Guid.NewGuid for its single default row.
                // Fix only this seed identity so rebuilding scripts is deterministic.
                InsertDataOperation seed = migration.UpOperations.OfType<InsertDataOperation>().Single();
                if (seed.Table != "backpack_reliquary_score_config" || seed.Values.GetLength(0) != 1)
                {
                    throw new InvalidOperationException("Review the default score configuration seed before regenerating migrations.");
                }
                seed.Values[0, Array.IndexOf(seed.Columns, "InnerId")] = new Guid("01D3D65E-56DB-4730-9474-575F65133FBA");
            }
            // Raw migration SQL need not end in a semicolon because EF executes each
            // command separately. Preserve those boundaries when emitting a single script.
            IReadOnlyList<MigrationCommand> commands = sqlGenerator.Generate(migration.UpOperations, modelInitializer.Initialize(migration.TargetModel), MigrationsSqlGenerationOptions.Script | MigrationsSqlGenerationOptions.NoTransactions);
            string sql = string.Concat(commands.Select(command => command.CommandText.TrimEnd().TrimEnd(';') + ";\n\n"));
            sql += history.GetInsertScript(new HistoryRow(id, ProductInfo.GetVersion()));
            sql = sql.Replace("\r\n", "\n");
            string hash = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(sql)));
            files[id + ".sql"] = sql;
            catalog.Append($"        new(\"{id}\", \"Hutao.Database.Schema.{id}.sql\", \"{hash}\"),\n");
        }
        catalog.Append("    ];\n}\n");
        files["DatabaseMigrations.g.cs"] = catalog.ToString();

        StringBuilder sources = new("<Project>\n  <ItemGroup>\n");
        foreach (string source in Directory.GetFiles(Path.Combine(app, "Migrations"), "*.cs").Order(StringComparer.Ordinal))
        {
            string hash = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(File.ReadAllText(source).Replace("\r\n", "\n"))));
            sources.Append($"    <DatabaseSchemaSource Include=\"$(MSBuildThisFileDirectory)../../../Migrations/{Path.GetFileName(source)}\" ExpectedHash=\"{hash}\" />\n");
        }
        sources.Append("  </ItemGroup>\n</Project>\n");
        files["SchemaSources.props"] = sources.ToString();

        if (!check)
        {
            Directory.CreateDirectory(output);
        }
        foreach ((string name, string content) in files)
        {
            string path = Path.Combine(output, name);
            if (check)
            {
                if (!File.Exists(path) || File.ReadAllText(path).Replace("\r\n", "\n") != content)
                {
                    throw new InvalidOperationException($"Regenerate database schema: {name} is missing or outdated.");
                }
            }
            else
            {
                File.WriteAllText(path, content, new UTF8Encoding(false));
            }
        }
        Console.WriteLine($"{(check ? "Verified" : "Generated")} {migrations.Length} migration SQL scripts and the source fingerprint manifest.");
        return 0;
    }
}
